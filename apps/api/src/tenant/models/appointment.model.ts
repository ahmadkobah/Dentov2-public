import { Schema, type Document, type Connection, type Model, type Types } from 'mongoose';
import { fieldEncryptionPlugin } from '../../utils/mongoose-field-encryption.plugin.js';

/**
 * Appointment Model — Tenant Database (tenant_{slug})
 *
 * Per V2_DATABASE.md §6.1 — appointments collection
 * Per DENTO_V2_MASTER_PLAN.md — Appointment Calendar
 *
 * Status flow: booked → confirmed → arrived → in_progress → completed
 *              booked → cancelled / no_show / rescheduled
 */

// ── Types ───────────────────────────────────────────────────

export interface IAppointment extends Document {
  patientId: Types.ObjectId;
  doctorId: Types.ObjectId;
  branchId: Types.ObjectId;
  serviceId?: Types.ObjectId;
  appointmentTypeId?: Types.ObjectId;

  // Scheduling
  date: Date; // Date only (normalized to midnight)
  startTime: string; // "HH:mm"
  endTime: string; // "HH:mm"
  durationMinutes: number;
  chairNumber?: number;

  // Status
  status:
    | 'booked'
    | 'confirmed'
    | 'arrived'
    | 'in_progress'
    | 'completed'
    | 'no_show'
    | 'cancelled'
    | 'rescheduled';
  type: 'consultation' | 'follow_up' | 'treatment' | 'emergency' | 'checkup';

  // Notes
  reason?: string;
  notes?: string;
  internalNotes?: string; // Staff-only

  // Source
  source: 'admin' | 'website' | 'phone' | 'walk_in' | 'referral' | 'whatsapp' | 'recurring';

  // Recurrence — set when generated by the recurring-appointments engine
  recurringRuleId?: Types.ObjectId; // → recurring_appointment_rules

  // Reminders
  isReminderSent: boolean;
  reminderSentAt?: Date;
  reminderSent?: Map<string, boolean>;

  // Financial
  consultationFee?: number;
  isPaid: boolean;

  // Cancellation / Reschedule
  cancelledBy?: Types.ObjectId;
  cancellationReason?: string;
  rescheduledToId?: Types.ObjectId; // → appointments

  // Timing Tracking
  arrivedAt?: Date;
  startedAt?: Date;
  completedAt?: Date;

  // Walk-in
  isWalkIn: boolean;

  isActive: boolean;
  createdBy: Types.ObjectId;
  updatedBy?: Types.ObjectId;
  createdAt: Date;
  updatedAt: Date;
}

// ── Schema ──────────────────────────────────────────────────

const appointmentSchema = new Schema<IAppointment>(
  {
    patientId: { type: Schema.Types.ObjectId, ref: 'Patient', required: true },
    doctorId: { type: Schema.Types.ObjectId, ref: 'Doctor', required: true },
    branchId: { type: Schema.Types.ObjectId, ref: 'Branch', required: true },
    serviceId: { type: Schema.Types.ObjectId },
    appointmentTypeId: { type: Schema.Types.ObjectId, ref: 'AppointmentType' },

    // Scheduling
    date: { type: Date, required: true },
    startTime: { type: String, required: true }, // HH:mm
    endTime: { type: String, required: true }, // HH:mm
    durationMinutes: { type: Number, required: true, default: 30 },
    chairNumber: Number,

    // Status
    status: {
      type: String,
      enum: [
        'booked',
        'confirmed',
        'arrived',
        'in_progress',
        'completed',
        'no_show',
        'cancelled',
        'rescheduled',
      ],
      default: 'booked',
      required: true,
    },
    type: {
      type: String,
      default: 'consultation',
    },

    // Notes
    reason: String,
    notes: String,
    internalNotes: String,

    // Source
    source: {
      type: String,
      enum: ['admin', 'website', 'phone', 'walk_in', 'referral', 'whatsapp', 'recurring'],
      default: 'admin',
    },

    // Recurrence
    recurringRuleId: { type: Schema.Types.ObjectId, ref: 'RecurringAppointmentRule' },

    // Reminders
    isReminderSent: { type: Boolean, default: false },
    reminderSentAt: Date,
    reminderSent: { type: Map, of: Boolean, default: {} },

    // Financial
    consultationFee: Number,
    isPaid: { type: Boolean, default: false },

    // Cancellation / Reschedule
    cancelledBy: { type: Schema.Types.ObjectId },
    cancellationReason: String,
    rescheduledToId: { type: Schema.Types.ObjectId, ref: 'Appointment' },

    // Timing Tracking
    arrivedAt: Date,
    startedAt: Date,
    completedAt: Date,

    // Walk-in
    isWalkIn: { type: Boolean, default: false },

    isActive: { type: Boolean, default: true },
    createdBy: { type: Schema.Types.ObjectId, required: true },
    updatedBy: { type: Schema.Types.ObjectId },
  },
  {
    timestamps: true,
  },
);

// ── Indexes ─────────────────────────────────────────────────

// Calendar query: date + doctor + time
appointmentSchema.index({ date: 1, doctorId: 1, startTime: 1 });

// Patient history
appointmentSchema.index({ patientId: 1, date: -1 });

// Branch schedule
appointmentSchema.index({ branchId: 1, date: 1, status: 1 });

// Status-based queries
appointmentSchema.index({ status: 1, date: 1 });

// Doctor schedule (for conflict detection)
appointmentSchema.index({ doctorId: 1, date: 1, status: 1 });

// Recurring-rule occurrences (for regeneration / cleanup)
appointmentSchema.index({ recurringRuleId: 1, date: 1 });

// Phase 0.3 — Atomic slot lock: prevent two concurrent bookings
// from claiming the same {doctor, date, startTime} when active.
// Cancelled / no_show / rescheduled slots are excluded so the slot can be re-used.
appointmentSchema.index(
  { doctorId: 1, date: 1, startTime: 1 },
  {
    unique: true,
    name: 'doctor_slot_unique_active',
    partialFilterExpression: {
      status: { $in: ['booked', 'confirmed', 'arrived', 'in_progress'] },
    },
  },
);

// ── Field-Level Encryption (HIPAA/GDPR — C-1) ──────────────────
appointmentSchema.plugin(fieldEncryptionPlugin, {
  fields: ['reason', 'notes', 'internalNotes', 'cancellationReason'],
});

// ── Model Factory ───────────────────────────────────────────

export function getAppointmentModel(connection: Connection): Model<IAppointment> {
  return (connection.models.Appointment ||
    connection.model('Appointment', appointmentSchema)) as Model<IAppointment>;
}

export type AppointmentModel = ReturnType<typeof getAppointmentModel>;
